/// Spacing values shared by Dartelier components.
///
/// Values are logical pixels. Keep this scale small and intentional; add a
/// value only when repeated design needs cannot be expressed with the existing
/// steps.
abstract final class DartelierSpacing {
  static const double xxs = 4;
  static const double xs = 8;
  static const double sm = 12;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 48;
}
